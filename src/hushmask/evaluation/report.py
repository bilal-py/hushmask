"""Turn evaluation JSON into the markdown tables in docs/eval/RESULTS.md."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..entities import EntityType

HEADER = """# Evaluation results

Generated by `hushmask eval`. Method and caveats: [README.md](README.md). Re-run with the commands there;
every run is seeded, so the same command gives the same numbers.

"""


def write_results(out_dir: Path) -> Path:
    """Rebuild RESULTS.md from every JSON result in the folder."""
    sections = [HEADER]
    for path in sorted(out_dir.glob("detect-*.json")):
        run = json.loads(path.read_text(encoding="utf-8"))
        sections.append(detection_markdown(run["title"], run))
    for path in sorted(out_dir.glob("task-*.json")):
        sections.append(task_markdown(json.loads(path.read_text(encoding="utf-8"))))
    target = out_dir / "RESULTS.md"
    target.write_text("\n".join(sections), encoding="utf-8")
    return target


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def detection_markdown(title: str, run: dict[str, Any]) -> str:
    setups: dict[str, Any] = run["setups"]
    lines = [f"### {title}", "", run["description"], ""]
    lines += [
        "| Setup | Values | Leaked or partly visible | Over-masked spans | Merchants damaged | ms / doc |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, r in setups.items():
        merchants = f"{r['keep_damaged']} / {r['keep_total']}" if r["keep_total"] else "n/a"
        lines.append(
            f"| {name} | {r['values']} | {pct(r['leak_rate'])} | {r['false_positives']} | {merchants} | "
            f"{r['ms_per_doc']} |"
        )
    best_name, best = list(setups.items())[-1]
    lines += ["", f"Leaks by type, *{best_name}*:", "", "| Type | Values | Protected | Partly visible | Leaked |"]
    lines.append("|---|---:|---:|---:|---:|")
    for label, t in best["per_type"].items():
        lines.append(f"| {label} | {t['total']} | {t['protected']} | {t['partial']} | {t['leaked']} |")
    if best["out_of_scope"]:
        claimed = {str(t) for t in EntityType}
        ordered = sorted(best["out_of_scope"].items(), key=lambda kv: -kv[1]["total"])
        kept = [f"{label} {o['protected']}/{o['total']}" for label, o in ordered if label in claimed]
        unclaimed = [f"{label} {o['protected']}/{o['total']}" for label, o in ordered if label not in claimed]
        if kept:
            lines += ["", f"Left visible on purpose by this preset (hidden anyway / total): {', '.join(kept)}."]
        if unclaimed:
            lines += ["", f"Kinds hushmask doesn't detect (hidden anyway / total): {', '.join(unclaimed)}."]
    if best["false_positive_examples"]:
        lines += ["", "Examples of over-masking: " + "; ".join(f"`{e}`" for e in best["false_positive_examples"][:6])]
    if best["keep_damaged_examples"]:
        lines += ["", "Merchants damaged: " + ", ".join(f"`{e}`" for e in best["keep_damaged_examples"][:6])]
    return "\n".join(lines) + "\n"


def task_markdown(run: dict[str, Any]) -> str:
    lines = [
        "### Does masking cost the AI accuracy?",
        "",
        f"{run['statements']} synthetic statements categorized by `{run['model']}`, temperature 0, once without "
        "and once with hushmask (finance preset, holder's name and address listed"
        f"{', names model on' if run.get('ner') else ''}).",
        "",
        "| Condition | Transactions | Category accuracy | People named correctly | Wrong count | s / statement |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, r in run["conditions"].items():
        lines.append(
            f"| {name} | {r['transactions']} | {pct(r['category_accuracy'])} | {pct(r['people_named_correctly'])} | "
            f"{r['statements_with_wrong_count']} | {r['seconds_per_statement']} |"
        )
    for name, r in run["conditions"].items():
        if r["top_mistakes"]:
            mistakes = ", ".join(f"{k} ({v})" for k, v in r["top_mistakes"].items())
            lines += ["", f"Most common mistakes {name}: {mistakes}."]
    return "\n".join(lines) + "\n"
